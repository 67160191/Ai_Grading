// Parse lines
const lines = rawStudentsText.trim().split("\n");
const students = [];
const seen = new Set();

for (const line of lines) {
  const parts = line.trim().split(/\s+/);
  if (parts.length >= 3) {
    const studentId = parts[1].trim();
    const name = parts.slice(2).join(" ").trim();
    if (studentId && name) {
      if (!seen.has(studentId)) {
        seen.add(studentId);
        students.push({ studentId, name });
      } else {
        console.warn(`Duplicate studentId found: ${studentId}`);
      }
    }
  }
}

console.log(`Parsed ${students.length} unique students.`);

// Transaction to delete old students and add new ones
const tx = db.transaction(() => {
  // 1. Get old student IDs
  const oldStudents = db.prepare("SELECT id FROM users WHERE role = 'student'").all();
  const oldIds = oldStudents.map((s) => s.id);

  if (oldIds.length > 0) {
    const placeholders = oldIds.map(() => "?").join(",");
    // Delete foreign key records first if any
    db.prepare(`DELETE FROM enrollments WHERE student_id IN (${placeholders})`).run(...oldIds);
    db.prepare(`DELETE FROM exam_submissions WHERE student_id IN (${placeholders})`).run(...oldIds);
    db.prepare(`DELETE FROM submissions WHERE student_id IN (${placeholders})`).run(...oldIds);
    db.prepare(`DELETE FROM users WHERE id IN (${placeholders})`).run(...oldIds);
    console.log(`Removed ${oldIds.length} old student(s).`);
  }

  // 2. Insert new students
  const insertUser = db.prepare(
    "INSERT INTO users (name, username, password, role) VALUES (?, ?, ?, ?)"
  );

  for (const s of students) {
    const hashedPassword = bcrypt.hashSync(s.studentId, 10);
    insertUser.run(s.name, s.studentId, hashedPassword, "student");
  }

  console.log(`Successfully added ${students.length} students.`);
});

tx();

const finalCount = db.prepare("SELECT count(*) as count FROM users WHERE role = 'student'").get();
console.log(`Final student count in database: ${finalCount.count}`);
